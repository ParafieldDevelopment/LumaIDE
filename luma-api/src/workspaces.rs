use crate::CoreAPI;
use anyhow::{Context, Result};
use serde::{Deserialize, Serialize};
use std::collections::HashMap;
use std::path::Path;
use std::time::{SystemTime, UNIX_EPOCH};

/// Persisted recent-workspace list, keyed by workspace id.
#[derive(Debug, Default, Serialize, Deserialize)]
#[serde(transparent)]
pub struct RecentProjects {
    pub map: HashMap<String, WorkspaceFace>,
}
#[derive(Debug, Clone, Default, Serialize, Deserialize)]
pub struct WorkspaceFace {
    /// Public/workspace id. Serialized as `project_uuid` for IPC compatibility.
    #[serde(rename = "project_uuid", alias = "id", default)]
    pub id: String,

    #[serde(default)]
    pub title: String,

    #[serde(default)]
    pub path: String,

    /// Optional workspace logo. Serialized as `icon_path` for IPC compatibility.
    #[serde(
        rename = "icon_path",
        alias = "logo_path",
        default,
        skip_serializing_if = "Option::is_none"
    )]
    pub logo_path: Option<String>,

    /// Derived from `.git/HEAD` when the face is refreshed.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub git_branch: Option<String>,

    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub last_opened_at: Option<u64>,
}

impl WorkspaceFace {
    pub fn new(id: impl Into<String>, title: impl Into<String>, path: impl Into<String>) -> Self {
        Self {
            id: id.into(),
            title: title.into(),
            path: path.into(),
            ..Self::default()
        }
    }

    pub fn root(&self) -> &Path {
        Path::new(&self.path)
    }

    pub fn with_logo(mut self, logo: Option<String>) -> Self {
        self.logo_path = logo;
        self
    }

    pub fn with_git_branch(mut self, branch: Option<String>) -> Self {
        self.git_branch = branch;
        self
    }

    pub fn mark_opened(mut self) -> Self {
        self.last_opened_at = Some(unix_timestamp());
        self
    }
}

/// An actually opened workspace.
///
/// `face` is flattened during serialization, so Tauri continues to emit the
/// same flat JSON shape the frontend already consumes.
#[derive(Debug, Clone, Default, Serialize, Deserialize)]
pub struct Workspace {
    #[serde(flatten)]
    pub face: WorkspaceFace,

    /// Project type id chosen in the New Workspace wizard (e.g. `luau`).
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub project_type: Option<String>,

    /// Runtime id chosen for the project type (e.g. `lua-5.4`).
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub runtime: Option<String>,

    /// Template id the workspace was created from (e.g. `hello-world`).
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub template: Option<String>,

    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub created_at: Option<u64>,
}

impl Workspace {
    #[allow(clippy::too_many_arguments)]
    pub fn new(
        face: WorkspaceFace,
        project_type: Option<String>,
        runtime: Option<String>,
        template: Option<String>,
        created_at: Option<u64>,
    ) -> Self {
        Self {
            face,
            project_type,
            runtime,
            template,
            created_at,
        }
    }

    pub fn face(&self) -> &WorkspaceFace {
        &self.face
    }

    pub fn root(&self) -> &Path {
        self.face.root()
    }

    /// Run the operations associated with opening a workspace: load its
    /// configuration through the core API, then notify registered listeners.
    pub fn load(&self, core: &dyn CoreAPI) -> Result<()> {
        core.open_workspace(self.root())
            .context("Failed to load workspace configuration")?;
        core.notify_workspace_loaded();
        Ok(())
    }
}

/// A file generated by a workspace template.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct TemplateFile {
    pub path: String,
    pub content: String,
}

pub fn unix_timestamp() -> u64 {
    SystemTime::now()
        .duration_since(UNIX_EPOCH)
        .unwrap_or_default()
        .as_secs()
}
